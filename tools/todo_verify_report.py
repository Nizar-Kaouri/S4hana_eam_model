#!/usr/bin/env python3
"""Collect every TODO-VERIFY marker and render the ranked table in BATCH_REPORT.md.

Marker format (one line, in any source/test/tool file):
    // TODO-VERIFY[<risk>] <AREA>-<NNN>: what must be confirmed on a real system   (CDS)
    "! TODO-VERIFY[<risk>] <AREA>-<NNN>: ...                                       (ABAP)
    # TODO-VERIFY[<risk>] <AREA>-<NNN>: ...                                        (Python)
Risk: H = likely to fail activation / import, M = may fail or behave differently,
      L = cosmetic or unlikely to fail.

The table is written between the markers
    <!-- TODO-VERIFY:BEGIN -->  and  <!-- TODO-VERIFY:END -->
Usage: python3 tools/todo_verify_report.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "BATCH_REPORT.md"
MARKER_RE = re.compile(r"TODO-VERIFY\[(?P<risk>[HML])\]\s+(?P<id>[A-Z]+-[A-Z0-9]+):\s*(?P<text>.*?)\s*$")
BEGIN, END = "<!-- TODO-VERIFY:BEGIN -->", "<!-- TODO-VERIFY:END -->"
RISK_ORDER = {"H": 0, "M": 1, "L": 2}
RISK_LABEL = {"H": "HIGH", "M": "MEDIUM", "L": "LOW"}


def collect():
    items = []
    for folder in ("src", "tests", "tools"):
        for path in sorted((ROOT / folder).rglob("*")):
            if not path.is_file() or path.suffix == ".pyc" or path.name in ("todo_verify_report.py", "validate_repo.py"):
                continue
            for i, line in enumerate(path.read_text(encoding="utf-8", errors="ignore").splitlines(), 1):
                m = MARKER_RE.search(line)
                if m:
                    items.append((m.group("risk"), m.group("id"), m.group("text").replace("|", "\\|"),
                                  f"{path.relative_to(ROOT)}:{i}"))
    items.sort(key=lambda it: (RISK_ORDER[it[0]], it[1]))
    return items


def render(items):
    counts = {r: sum(1 for it in items if it[0] == r) for r in "HML"}
    lines = [BEGIN, "",
             f"_Generated by `tools/todo_verify_report.py` - {len(items)} items "
             f"(HIGH {counts['H']}, MEDIUM {counts['M']}, LOW {counts['L']}). Do not edit by hand._", ""]
    for risk in "HML":
        group = [it for it in items if it[0] == risk]
        if not group:
            continue
        lines += [f"#### {RISK_LABEL[risk]}", "", "| ID | What to verify | Location |", "|---|---|---|"]
        lines += [f"| {it[1]} | {it[2]} | `{it[3]}` |" for it in group]
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main():
    text = REPORT.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{REPORT.name}: markers {BEGIN} / {END} not found")
    new = text[: text.index(BEGIN)] + render(collect()) + text[text.index(END) + len(END):]
    if "--check" in sys.argv:
        if new != text:
            print("BATCH_REPORT.md TODO-VERIFY table is out of date - run python3 tools/todo_verify_report.py")
            sys.exit(1)
        return
    REPORT.write_text(new, encoding="utf-8")
    print(f"updated {REPORT.name}")


if __name__ == "__main__":
    main()
