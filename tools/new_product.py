#!/usr/bin/env python3
"""Create the folder skeleton for a new product package under /packages/<name>.

Usage:
  python3 tools/new_product.py <name> --prefix ZFAAV_ --package ZFAA_VDM --title "Asset Accounting" \
      [--area FI-AA] [--description "..."]

Creates library.json, .abapgit.xml, abaplint.json (CDS naming for the prefix), src/package.devc.xml,
modules/, docs/views/, tests/abap/, README.md, BATCH_REPORT.md and ACTIVATION_CHECKLIST.md (with the
generator markers), so that every shared tool works on the empty product right away.
Refuses to overwrite an existing product.
"""
import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
EAM = REPO / "packages" / "eam"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Scaffold a new product package")
    ap.add_argument("name", help="folder name, lower case, e.g. fi_aa")
    ap.add_argument("--prefix", required=True, help="object prefix, e.g. ZFAA_")
    ap.add_argument("--package", required=True, help="ABAP package, e.g. ZFAA_VDM")
    ap.add_argument("--title", required=True, help="product title, e.g. 'Asset Accounting'")
    ap.add_argument("--area", default="", help="SAP area code, e.g. FI-AA")
    ap.add_argument("--description", default="", help="one-line description")
    a = ap.parse_args(argv)

    if not re.fullmatch(r"[a-z][a-z0-9_]*", a.name):
        sys.exit("name must be lower case letters, digits and underscores")
    if not re.fullmatch(r"Z[A-Z0-9]{2,4}_", a.prefix):
        sys.exit("prefix must look like ZXXX_ (Z + 2-4 characters + underscore)")
    root = REPO / "packages" / a.name
    if root.exists():
        sys.exit(f"{root} already exists")

    for d in ("src", "modules", "docs/views", "tests/abap"):
        (root / d).mkdir(parents=True)
    (root / "modules" / ".gitkeep").write_text("")
    (root / "docs" / "views" / ".gitkeep").write_text("")
    (root / "tests" / "abap" / ".gitkeep").write_text("")

    eam_lib = json.loads((EAM / "library.json").read_text())
    lib = {
        "_comment": eam_lib["_comment"],
        "phase": "no-system",
        "layer_prefixes": {"basic": "B_", "composite": "I_", "consumption": "C_"},
        "prefix": a.prefix,
        "package": a.package,
        "package_description": f"{a.title} CDS Virtual Data Model",
        "product_title": a.title,
        "sap_area": a.area,
        "target_release": eam_lib["target_release"],
        "max_object_name_length": eam_lib["max_object_name_length"],
        "reserve_prefix_chars": eam_lib.get("reserve_prefix_chars", 1),
    }
    (root / "library.json").write_text(json.dumps(lib, indent=2) + "\n")
    (root / ".abapgit.xml").write_text((EAM / ".abapgit.xml").read_text())

    lint = json.loads((EAM / "abaplint.json").read_text())
    lint["syntax"]["errorNamespace"] = f"^({a.prefix}|LCL_|TY_|LIF_)"
    lint["rules"]["cds_naming"] = {k: v.replace("ZEAM_", a.prefix) for k, v in lint["rules"]["cds_naming"].items()}
    (root / "abaplint.json").write_text(json.dumps(lint, indent=2) + "\n")

    devc = (EAM / "src" / "package.devc.xml").read_text()
    devc = re.sub(r"<CTEXT>.*?</CTEXT>", f"<CTEXT>{a.title} CDS Virtual Data Model</CTEXT>", devc)
    (root / "src" / "package.devc.xml").write_text(devc)

    (root / "README.md").write_text(f"""# {a.title} ({a.area or a.name}) - CDS virtual data model

> **Status: planned.** Product skeleton only - no views yet. See `PRODUCT_CHECKLIST.md` in the
> repository root for the planned modules and the release checks to do first.

{a.description}

| | |
|---|---|
| Product folder | `packages/{a.name}` |
| Object prefix | `{a.prefix}` |
| ABAP package | `{a.package}` |
| Target release | {lib['target_release']} |

Layout, layering rules, module rules and tooling are the same as in the EAM product
(`packages/eam/README.md`). Every tool takes `--product {a.name}`:

```bash
python3 tools/check_all.py --only {a.name}
python3 build_package.py --product {a.name} --list
```
""")
    (root / "BATCH_REPORT.md").write_text(f"""# Batch report - {a.title}

Running log of what was generated, what was checked offline, and what must still be verified on a
real SAP S/4HANA 2025 system.

> **Nothing has been generated yet.**

## Open TODO-VERIFY items (all batches, ranked by risk)

<!-- TODO-VERIFY:BEGIN -->
<!-- TODO-VERIFY:END -->

## Verification log

_Empty._
""")
    (root / "ACTIVATION_CHECKLIST.md").write_text(f"""# Activation checklist - {a.title}

> **Nothing in this product has been activated.** The tables below are generated by
> `tools/gen_checklist.py --product {a.name}` once modules exist.

<!-- CHECKLIST:BEGIN -->
<!-- CHECKLIST:END -->
""")
    print(f"created packages/{a.name} (prefix {a.prefix}, package {a.package})")


if __name__ == "__main__":
    main()
