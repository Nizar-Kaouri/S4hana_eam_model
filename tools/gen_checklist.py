#!/usr/bin/env python3
"""Generate the tables of ACTIVATION_CHECKLIST.md from module.json files and object references.

Writes between <!-- CHECKLIST:BEGIN --> and <!-- CHECKLIST:END -->:
  - SAP released views to check per module
  - per batch: activation order (DDLS, DCLS, DDLX, CLAS) with dependencies, as checkboxes
Usage: python3 tools/gen_checklist.py [--check]
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import vdm_paths  # noqa: E402  (consumes --product)

ROOT = vdm_paths.PRODUCT_ROOT
sys.path.insert(0, str(vdm_paths.REPO))
import build_package as bp  # noqa: E402

FILE = ROOT / "ACTIVATION_CHECKLIST.md"
BEGIN, END = "<!-- CHECKLIST:BEGIN -->", "<!-- CHECKLIST:END -->"
KIND = {"DDLS": "Data definitions (DDLS)", "DCLS": "Access controls (DCLS)",
        "DDLX": "Metadata extensions (DDLX)", "CLAS": "ABAP Unit test classes (CLAS, only with --with-tests)"}


def render():
    library = bp.load_library()
    prefix = library["prefix"]
    modules = bp.load_modules()
    links = bp.collect_link_views(modules)
    _, objects, _, _ = bp.select_objects(sorted(modules), modules, with_tests=True)
    order = bp.activation_order(objects, prefix)
    pos = {(t, n.upper()): i for i, (t, n, _) in enumerate(order, 1)}

    def batch_of(owner, name):
        if owner == "link":
            req = links[name]["requires_modules"]
            return max(modules[m].get("batch", 0) for m in req)
        return modules[owner].get("batch", 0)

    lines = [BEGIN, "",
             "_Generated by `tools/gen_checklist.py` from module.json files and object references. "
             "Do not edit by hand._", "",
             "### SAP released views to check before import", "",
             "| Batch | Module | SAP views |", "|---|---|---|"]
    for m in sorted(modules.values(), key=lambda x: (x.get("batch", 0), x["name"])):
        views = ", ".join(f"`{v}`" for v in m.get("sap_released_views", [])) or "- (built on other modules only)"
        deps = m.get("hard_dependencies", [])
        dep_txt = f" (needs {', '.join(f'`{d}`' for d in deps)})" if deps else ""
        lines.append(f"| {m.get('batch', '?')} | `{m['name']}`{dep_txt} | {views} |")
    lines.append("")

    no_dcl = []
    for m in modules.values():
        no_dcl += list(m.get("no_dcl_by_design", {}))
        no_dcl += [lk["name"] for lk in m.get("link_views", []) if lk.get("no_dcl_reason")]

    batches = sorted({batch_of(o, n) for _, n, o in order})
    for b in batches:
        lines += [f"### Batch {b}", ""]
        for kind in ("DDLS", "DCLS", "DDLX", "CLAS"):
            rows = [(i, t, n, o) for i, (t, n, o) in enumerate(order, 1) if t == kind and batch_of(o, n) == b]
            if not rows:
                continue
            lines += [f"#### {KIND[kind]}", "", "| # | Object | Module | Depends on (shipped objects) | Done |",
                      "|---|---|---|---|---|"]
            for i, t, n, o in rows:
                refs = sorted(bp.references(t, n, prefix))
                deps = [f"#{pos[('DDLS', r)]}" for r in refs if ("DDLS", r) in pos]
                deps += [f"role #{pos[('DCLS', r)]}" for r in refs if t == "DCLS" and ("DCLS", r) in pos]
                if t in ("DCLS", "DDLX") and ("DDLS", n.upper()) in pos:
                    deps.insert(0, f"view #{pos[('DDLS', n.upper())]}")
                owner = "**link**" if o == "link" else o
                lines.append(f"| {i} | `{n}` | {owner} | {', '.join(dict.fromkeys(deps)) or '-'} | [ ] |")
            lines.append("")
        q = sorted(n for n in no_dcl if any(n == on and batch_of(oo, on) == b for _, on, oo in order))
        if q:
            lines += ["No DCL by design (transient queries): " + ", ".join(f"`{n}`" for n in q) + ".", ""]
    lines.append(END)
    return "\n".join(lines)


def main():
    text = FILE.read_text(encoding="utf-8")
    new = text[: text.index(BEGIN)] + render() + text[text.index(END) + len(END):]
    if "--check" in sys.argv:
        if new != text:
            print("ACTIVATION_CHECKLIST.md is out of date - run python3 tools/gen_checklist.py")
            sys.exit(1)
        return
    FILE.write_text(new, encoding="utf-8")
    print("updated " + FILE.name)


if __name__ == "__main__":
    main()
